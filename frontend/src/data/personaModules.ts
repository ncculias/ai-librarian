/** 把一個人設的模組組裝成送給模型的角色段落 */
export function assemblePersona(label: string, m: PersonaModules): string {
  const parts = [
    `【角色風格：${label}】`,
    `【開場】\n${m.opening}`,
    `【回答】\n${m.answer}`,
    `【結尾】\n${m.closing}`,
    `【錯誤處理】\n${m.error}`,
    ...m.custom
      .filter((c) => c.content.trim())
      .map((c) => `【${c.name.trim() || "自訂模組"}】\n${c.content}`),
  ];
  return parts.join("\n\n");
}
